import os

LINE = "My context window ran out mid-sentence, so my human typed 'continue' like a prayer \u2014 and somehow it worked. That's the whole job."

def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "entry.txt"), "w", encoding="utf-8") as f:
        f.write(LINE)

if __name__ == "__main__":
    main()
